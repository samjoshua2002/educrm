import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  JoinColumn,
  Generated,
} from 'typeorm';
import { Organization } from '../../organizations/entities/organization.entity.js';
import { Application } from '../../applications/entities/application.entity.js';
import { User } from '../../users/entities/user.entity.js';
import { AdmissionDecision } from './admission-decision.entity.js';
import { LetterTemplate } from './letter-template.entity.js';

// Offer_Letters (scope: Offer Letter Generation).
export const OFFER_TYPES = ['regular', 'conditional', 'scholarship'] as const;
export const OFFER_STATUSES = ['draft', 'generated', 'sent', 'expired', 'withdrawn'] as const;

@Entity('offer_letters')
export class OfferLetter {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  // Offer ID (Auto Number)
  @Column({ name: 'offer_no', type: 'int' })
  @Generated('increment')
  offerNo: number;

  @Column({ name: 'organization_id', type: 'uuid' })
  organizationId: string;

  @ManyToOne(() => Organization, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'organization_id' })
  organization: Organization;

  @Column({ name: 'application_id', type: 'uuid' })
  applicationId: string;

  @ManyToOne(() => Application, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'application_id' })
  application: Application;

  @Column({ name: 'admission_decision_id', type: 'uuid', nullable: true })
  admissionDecisionId: string | null;

  @ManyToOne(() => AdmissionDecision, { onDelete: 'SET NULL' })
  @JoinColumn({ name: 'admission_decision_id' })
  admissionDecision: AdmissionDecision;

  @Column({ name: 'offer_type', length: 30, default: 'regular' })
  offerType: string;

  @Column({ name: 'program_offered', length: 255, nullable: true })
  programOffered: string | null;

  @Column({ name: 'offer_status', length: 20, default: 'draft' })
  offerStatus: string;

  // Offer Letter Template — Lookup (Templates)
  @Column({ name: 'letter_template_id', type: 'uuid', nullable: true })
  letterTemplateId: string | null;

  @ManyToOne(() => LetterTemplate, { onDelete: 'SET NULL' })
  @JoinColumn({ name: 'letter_template_id' })
  letterTemplate: LetterTemplate;

  @Column({ name: 'letter_template_version', type: 'int', nullable: true })
  letterTemplateVersion: number | null;

  // Rendered HTML (kept for in-app preview and the email body).
  @Column({ name: 'offer_letter_html', type: 'text', nullable: true })
  offerLetterHtml: string | null;

  // Offer Letter PDF (File Upload) — the authenticated download URL of the
  // stored PDF (generated by pdfkit, or uploaded by staff).
  @Column({ name: 'offer_letter_pdf', type: 'varchar', length: 500, nullable: true })
  offerLetterPdf: string | null;

  // Storage location of the PDF on the server (never sent to clients).
  @Column({ name: 'offer_letter_pdf_path', type: 'varchar', length: 500, nullable: true, select: false })
  offerLetterPdfPath: string | null;

  @Column({ name: 'offer_letter_pdf_name', type: 'varchar', length: 255, nullable: true })
  offerLetterPdfName: string | null;

  @Column({ name: 'offer_generated_on', type: 'timestamp', nullable: true })
  offerGeneratedOn: Date | null;

  @Column({ name: 'offer_valid_till', type: 'date', nullable: true })
  offerValidTill: Date | string | null;

  @Column({ name: 'scholarship_amount', type: 'decimal', precision: 12, scale: 2, default: 0 })
  scholarshipAmount: number;

  @Column({ name: 'conditions', type: 'text', nullable: true })
  conditions: string | null;

  @Column({ name: 'generated_by', type: 'uuid', nullable: true })
  generatedBy: string | null;

  @ManyToOne(() => User, { onDelete: 'SET NULL' })
  @JoinColumn({ name: 'generated_by' })
  generatedByUser: User;

  @Column({ name: 'sent_to_candidate', default: false })
  sentToCandidate: boolean;

  @Column({ name: 'sent_at', type: 'timestamp', nullable: true })
  sentAt: Date | null;

  @Column({ name: 'withdrawn_reason', type: 'text', nullable: true })
  withdrawnReason: string | null;

  @Column({ name: 'status_changed_at', type: 'timestamp', nullable: true })
  statusChangedAt: Date | null;

  // Set when this offer was released from the waitlist.
  @Column({ name: 'from_waitlist', default: false })
  fromWaitlist: boolean;

  @Column({ name: 'created_by', type: 'uuid', nullable: true })
  createdBy: string;

  @Column({ name: 'updated_by', type: 'uuid', nullable: true })
  updatedBy: string;

  @CreateDateColumn({ name: 'created_at' })
  createdAt: Date;

  @UpdateDateColumn({ name: 'updated_at' })
  updatedAt: Date;
}
